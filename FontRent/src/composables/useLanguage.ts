export type TranslationKey = keyof typeof messages.en

const storedLanguage = typeof window === 'undefined' ? null : window.localStorage.getItem('fontrent-language')
const language = ref<Language>(storedLanguage === 'my' ? 'my' : 'en')

function updateDocumentLanguage(value: Language) {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = value === 'my' ? 'my' : 'en'
    document.title =
      value === 'my' ? 'NestFlow — အိမ်ရာနှင့် အငှားစာချုပ်များ' : 'NestFlow — Homes & Leases'
  }
}

updateDocumentLanguage(language.value)

export function useLanguage() {
  function t(key: TranslationKey): string {
    return messages[language.value][key]
  }

  function toggleLanguage() {
    language.value = language.value === 'en' ? 'my' : 'en'
    if (typeof window !== 'undefined') {
      window.localStorage.setItem('fontrent-language', language.value)
    }
    updateDocumentLanguage(language.value)
  }

  return { language, t, toggleLanguage }
}
